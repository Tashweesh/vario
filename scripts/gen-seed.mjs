// Generates supabase/seed.sql from the design's sample data (project/vairo-data.js).
// Usage: node scripts/gen-seed.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import * as D from '../project/vairo-data.js';

const q = (v) => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (Array.isArray(v)) return `array[${v.map(q).join(',')}]::text[]`;
  if (typeof v === 'object') return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const row = (vals) => `(${vals.map(q).join(', ')})`;
const insert = (table, cols, rows) => `insert into ${table} (${cols.join(', ')}) values\n  ${rows.map(row).join(',\n  ')};\n`;

const out = [];
out.push('-- GENERATED by scripts/gen-seed.mjs from project/vairo-data.js — sample data for local development.\n');

out.push(insert('public.areas', ['id', 'name', 'short', 'vibe', 'description', 'ppm', 'rent', 'img', 'x', 'y', 'tags', 'dna', 'sort'],
  D.areas.map((a, i) => [a.id, a.name, a.short, a.vibe, a.desc, a.ppm, a.rent, a.img, a.x, a.y, a.tags, a.dna, i])));

out.push(insert('public.developers', ['id', 'name', 'mono', 'founded', 'focus', 'delivered', 'units', 'description', 'phone', 'email'],
  D.devs.map((d) => [d.id, d.name, d.mono, d.founded, d.focus, d.delivered, d.units, d.desc, d.phone, d.email])));

const EN = { 'unique-tower': 'Unique Tower', 'dc-tower': 'DC Tower', 'tulip-tower': 'Tulip Tower', 'asco-village': 'Asco Village', 'idris-erbil': 'Idris Erbil', 'cedar-gardens': 'Cedar Gardens', 'zagros-hills': 'Zagros Hills', 'empire-world': 'Empire World' };
out.push(insert('public.projects', ['id', 'name', 'name_en', 'type', 'area_id', 'developer_id', 'status', 'progress', 'handover', 'floors', 'units', 'img', 'tagline', 'amenities', 'price_from', 'plan_down', 'plan_months', 'plan_handover', 'sort'],
  D.projects.map((p, i) => [p.id, p.name, EN[p.id] || null, p.type, p.area, p.dev, p.status, p.progress, p.handover, p.floors, p.units, p.img, p.tagline, p.amen, p.from, p.plan.down, p.plan.months, p.plan.handover, i])));
// "Tulip Tower progress is stale" shows up in the CMS dashboard.
out.push(`update public.projects set progress_updated_at = now() - interval '40 days' where id = 'tulip-tower';\n`);

// Tower explorer grid (same availability pattern as the prototype).
const UNIT = { A: [3, 186], B: [2, 128], C: [2, 128], D: [3, 165], E: [1, 92], F: [4, 240] };
const units = [];
for (const p of D.projects.filter((p) => p.type === 'tower')) {
  const base = p.from / 92;
  for (let n = 1; n <= p.floors; n++) {
    Object.entries(UNIT).forEach(([u, [beds, size]], j) => {
      const st = (n * 7 + j) % 5 === 0 ? 'sold' : (n + j) % 3 === 0 ? 'reserved' : 'free';
      units.push([p.id, n, u, beds, size, Math.round((size * base * (1 + 0.006 * n)) / 1000) * 1000, st]);
    });
  }
}
out.push(insert('public.project_units', ['project_id', 'floor', 'unit', 'beds', 'size', 'price', 'status'], units));

out.push(insert('public.agents', ['id', 'name', 'title', 'img', 'phone', 'sort'],
  D.agents.map((a, i) => [a.id, a.name, a.role, a.img, a.phone, i])));

// Staff accounts. Local-dev password for all of them: vairo-dev-2026
const STAFF = { alan: ['admin@vairo.iq', 'admin'], hevi: ['hevi@vairo.iq', 'editor'], sara: ['sara@vairo.iq', 'agent'], rebwar: ['rebwar@vairo.iq', 'agent'], dilshad: ['dilshad@vairo.iq', 'agent'] };
const uid = (n) => `00000000-0000-4000-8000-${String(n).padStart(12, '0')}`;
const staffIds = Object.keys(STAFF);
out.push(`-- local auth users (password: vairo-dev-2026)
insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, recovery_token, email_change_token_new, email_change)
values
  ${staffIds.map((k, i) => `('00000000-0000-0000-0000-000000000000', '${uid(i + 1)}', 'authenticated', 'authenticated', '${STAFF[k][0]}', crypt('vairo-dev-2026', gen_salt('bf')), now(), '{"provider":"email","providers":["email"]}', '{}', now(), now(), '', '', '', '')`).join(',\n  ')};
insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
values
  ${staffIds.map((k, i) => `('${uid(i + 1)}', '${uid(i + 1)}', '${uid(i + 1)}', '{"sub":"${uid(i + 1)}","email":"${STAFF[k][0]}","email_verified":true}', 'email', now(), now(), now())`).join(',\n  ')};
`);
out.push(insert('public.staff', ['agent_id', 'email', 'role'], staffIds.map((k) => [k, STAFF[k][0], STAFF[k][1]])));

const lcols = ['id', 'deal', 'type', 'area_id', 'project_id', 'agent_id', 'status', 'featured', 'featured_rank', 'beds', 'baths', 'size', 'plot', 'floor', 'total_floors', 'floors', 'terrace', 'frontage', 'land_use', 'use_type', 'age', 'condition', 'view_text', 'features', 'price', 'payment', 'rent', 'furnishing', 'deposit', 'available', 'plan_source', 'views', 'leads', 'listed_at'];
const FEATURES = ['كهرباء 24 ساعة', 'موقف مغطى', 'حراسة 24 ساعة', 'مصاعد', 'بلكونة', 'تكييف مركزي'];
let rank = 0;
out.push(insert('public.listings', lcols, D.listings.map((l) => [
  l.id, l.deal, l.type, l.area, l.proj || null, l.agent, l.status, !!l.featured, l.featured ? ++rank : null,
  l.beds ?? null, l.baths ?? null, l.size, l.plot ?? null, l.floor ?? null, l.totalFloors ?? null, l.floors ?? null, l.terrace ?? null, l.frontage ?? null,
  l.landUse ?? null, l.use ?? null, l.age ?? null, l.condition ?? null, l.view ?? null,
  l.type === 'land' ? [] : FEATURES.filter((f) => l.type !== 'villa' || f !== 'مصاعد'),
  l.price ?? null, l.payment ?? null, l.rent ?? null, l.furnishing ?? null, l.deposit ?? null, l.available ?? null,
  l.payment === 'installments' || l.payment === 'both' ? (l.proj ? 'project' : 'custom') : null,
  l.views, l.leads, l.listed,
])));
out.push(`update public.listings set plan_down = 20, plan_months = 36, plan_handover = 10 where plan_source = 'custom';
update public.listings set status_changed_at = now() - interval '12 days' where status = 'reserved';
update public.listings set status_changed_at = date_trunc('month', now()) + interval '2 days' where status = 'sold';
select setval('public.listing_sale_seq', 1009, false);
select setval('public.listing_rent_seq', 5005, false);
-- seed inserts happened without a signed-in user; give the change log a readable history
update public.listing_events set actor_name = 'سارا أحمد', created_at = now() - interval '3 weeks';
insert into public.listing_events (listing_id, kind, label, actor_name, created_at)
  select id, 'status', 'نُشر', 'هيفي رشيد', listed_at::timestamptz from public.listings where status <> 'draft';
`);

const media = [];
D.listings.forEach((l) => l.imgs.forEach((url, i) => media.push([l.id, 'photo', url, i])));
out.push(insert('public.listing_media', ['listing_id', 'kind', 'url', 'sort'], media));
out.push(`insert into public.listing_private (listing_id, owner_name, owner_phone) values ('VS-1001', 'محمد قادر', '0750 555 1212');\n`);

out.push(`insert into public.site_settings (id, home_areas, featured_project_id) values (1, array['center','ankawa','gulan','bakhtiari'], 'unique-tower');\n`);

// CRM
const AGO = { 'قبل 20 دقيقة': '20 minutes', 'قبل ساعتين': '2 hours', 'أمس': '1 day', 'قبل 3 أيام': '3 days', 'قبل يومين': '2 days', 'قبل أسبوع': '7 days', 'قبل 45 دقيقة': '45 minutes', 'قبل 5 ساعات': '5 hours' };
const cid = (id) => `00000000-0000-4000-9000-${String(id.slice(1)).padStart(12, '0')}`;
const dealOf = (lid) => D.listings.find((l) => l.id === lid).deal;
out.push(insert('public.contacts', ['id', 'name', 'phone', 'source', 'stage', 'score', 'deal', 'agent_id', 'budget', 'note'],
  D.contacts.map((c) => [cid(c.id), c.name, c.phone, c.source, c.stage, c.score, dealOf(c.interest), c.agent, c.budget, c.note])));
out.push(insert('public.contact_listings', ['contact_id', 'listing_id'], D.contacts.map((c) => [cid(c.id), c.interest])));
out.push(D.contacts.map((c) => `insert into public.activities (contact_id, kind, body, agent_id, created_at) values ('${cid(c.id)}', 'web', ${q('طلب من ' + c.source + ' — ' + c.interest + '\n«أريد معلومات أكثر عن هذا العقار»')}, null, now() - interval '${AGO[c.last]}' - interval '3 days');
${c.stage !== 'new' ? `insert into public.activities (contact_id, kind, body, agent_id, created_at) values ('${cid(c.id)}', 'call', 'مكالمة واردة · 6 دقائق — سأل عن الطابق والإطلالة.', ${q(c.agent)}, now() - interval '${AGO[c.last]}' - interval '1 day');\n` : ''}insert into public.activities (contact_id, kind, body, agent_id, created_at) values ('${cid(c.id)}', '${c.stage === 'new' ? 'system' : 'note'}', ${q(c.note)}, ${q(c.agent)}, now() - interval '${AGO[c.last]}');`).join('\n') + '\n');
out.push(`insert into public.activities (contact_id, kind, body, agent_id, due_at) values ('${cid('c1')}', 'task', 'اتصال متابعة بعد المعاينة', 'sara', date_trunc('day', now()) + interval '4 days 18 hours');
update public.contacts c set
  last_activity_at = coalesce((select max(created_at) from public.activities a where a.contact_id = c.id and a.kind <> 'task'), c.created_at),
  created_at = coalesce((select min(created_at) from public.activities a where a.contact_id = c.id), c.created_at),
  first_response_at = (select min(created_at) from public.activities a where a.contact_id = c.id and a.kind in ('note', 'call')),
  closed_at = case when c.stage = 'closed' then now() - interval '7 days' end;
`);

// Viewings: Saturday→Tuesday of the coming week, Erbil time.
const DOW = { 'السبت': 0, 'الأحد': 1, 'الاثنين': 2, 'الثلاثاء': 3, 'الأربعاء': 4 };
const VST = { 'مؤكدة': 'confirmed', 'بانتظار التأكيد': 'pending', 'إعادة معاينة': 'second' };
out.push(`with sat as (select (current_date + ((6 - extract(dow from current_date)::int + 7) % 7))::date as d)
insert into public.viewings (contact_id, listing_id, agent_id, scheduled_at, status)
select v.contact_id::uuid, v.listing_id, v.agent_id, ((sat.d + v.off) + v.t::time) at time zone 'Asia/Baghdad', v.status
from sat, (values
  ${D.viewings.map((v) => `(${q(cid(v.contact))}, ${q(v.listing)}, ${q(v.agent)}, ${DOW[v.day]}, ${q(v.time)}, ${q(VST[v.status])})`).join(',\n  ')}
) as v(contact_id, listing_id, agent_id, off, t, status);
`);

writeFileSync(fileURLToPath(new URL('../supabase/seed.sql', import.meta.url)), out.join('\n'));
console.log('wrote supabase/seed.sql');
